/** Main shot + two detail crops of the same photograph for the gallery. */
function gallery(src: string, alt: string): ProductImage[] {
  return [
    { src, alt },
    { src, alt: `${alt} — detail`, focal: [0.5, 0.5, 1.7] },
    { src, alt: `${alt} — close-up`, focal: [0.38, 0.42, 2.2] },
  ];
}

