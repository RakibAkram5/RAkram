let counter = 1000;
function make(s: Seed): Product {
  counter += 1;
  const { img, alt, ...rest } = s;
  return {
    ...rest,
    id: `p${counter}`,
    sku: `RK-${s.category.slice(0, 3).toUpperCase()}-${counter}`,
    images: gallery(img, alt),
    description:
      s.description ??
      `${s.shortDescription} Designed and quality-checked for everyday use, the ${s.name} pairs refined materials with considered details — a RAKRAM curation you will reach for season after season.`,
    highlights: s.highlights ?? [
      "Quality-inspected before dispatch",
      "7-day easy return policy (demo terms)",
      "Cash on Delivery available nationwide",
    ],
    specs: s.specs ?? {},
  };
}

